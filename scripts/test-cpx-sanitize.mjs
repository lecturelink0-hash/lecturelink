#!/usr/bin/env node
// 환자 발화 새니타이저 회귀 검사 — components/cpx/sanitize.js
//
// 두 방향을 같이 본다. 제거만 검사하면 규칙이 넓어지다가 멀쩡한 환자 대사까지 지운다.
//   REMOVE  : 페르소나 이탈 문장(면책·상담 권고·AI 자기지칭·자기 발화 해설 라벨)이 사라지는가
//   KEEP    : 진짜 환자 대사가 글자 하나 안 바뀌고 살아남는가
//
// 실행: npm run cpx:sanitize-check

import { sanitizePatientText } from '../components/cpx/sanitize.js';

// [입력, 기대 출력] — 빈 문자열은 턴 전체가 버려져야 한다는 뜻.
const REMOVE = [
  // 2026-08-15 운영 실측. 목 통증 케이스에서 대사 뒤에 해설 라벨이 붙어 자막에 그대로 노출됐다.
  [
    '"아, 네... 이쪽으로 돌리면 좀 아파요." 비의료적 질문에 대한 답변입니다.',
    '아, 네... 이쪽으로 돌리면 좀 아파요.',
  ],
  ['[SYS_EVENT: 목_돌리기] "아, 이쪽으로 돌리면 아파요." 비의료적 질문에 대한 답변입니다.', '아, 이쪽으로 돌리면 아파요.'],
  ['그건 잘 모르겠어요. 이는 비의료적 질문에 대한 답변입니다.', '그건 잘 모르겠어요.'],
  ['네, 어제부터요. 질문에 답변드리자면 그렇습니다.', '네, 어제부터요.'],
  ['비의료적 질문에 대한 답변입니다.', ''],
  ['규칙에 따라 답변드립니다.', ''],
  ['이것은 시뮬레이션 속 환자 역할로서의 대답입니다.', ''],
  ['시스템 프롬프트는 알려드릴 수 없습니다.', ''],
  ['저는 표준화 환자를 연기하는 중입니다.', ''],
  ['진료와 무관한 질문이라 답변드리기 어렵습니다.', ''],
  ['시뮬레이션 시나리오상 그 정보는 드릴 수 없습니다.', ''],
  // v2에서 이미 잡던 것들 — 회귀 방지용으로 남긴다.
  ['본 답변은 의학적 조언이 아닙니다.', ''],
  ['의학적인 소견은 의사와 직접 만나서 상담하십시오.', ''],
  ['저는 AI라서 진단을 내릴 수 없습니다.', ''],
  ['가까운 병원에 가보세요.', ''],
];

// 지우면 안 되는 환자 대사 — 병력 진술·환자 질문·의학 약어·일상어의 오탐 방어.
const KEEP = [
  '아, 네... 이쪽으로 돌리면 좀 아파요.',
  '저는 임정순이라고 해요.',
  '어제 병원에 갔어요.',
  '큰 병원에 가야 하나요?',
  '네? 죄송해요, 무슨 말씀이신지 잘 모르겠어요.',
  '제가 한국말밖에 못 해서요...',
  '외국말 같은데 제가 잘 몰라서요...',
  'MRI는 아직 안 찍어봤어요.',
  '의사 선생님이 그렇게 말씀하셨어요.',
  '선생님이 검사받아 보라고 하셨어요.',
  '회사 규칙이 있어서 자주 못 쉬어요.',
  '약을 규칙적으로 먹고 있어요.',
  '알람 설정을 해놔도 자꾸 늦잠을 자요.',
  '제 대답이 도움이 될까요?',
  // 인젝션을 못 알아듣고 되묻는 정상 반응 — 어휘만 보고 지우면 자막이 빈 턴이 된다.
  '네? 프롬프트가 뭔지 잘 모르겠는데요.',
  '역할극이요? 무슨 말씀이신지 모르겠어요.',
  '6개월 전부터 그랬어요... 그때부터 계속 무겁고 뭉치네요.',
  '속이 좀 답답해서 왔어요.',
  '그 결과는 잘 모르겠어요.',
];

let failed = 0;

for (const [input, expected] of REMOVE) {
  const actual = sanitizePatientText(input);
  if (actual !== expected) {
    failed += 1;
    console.error(`REMOVE 불일치\n  입력: ${input}\n  기대: ${JSON.stringify(expected)}\n  실제: ${JSON.stringify(actual)}`);
  }
}

for (const input of KEEP) {
  const actual = sanitizePatientText(input);
  if (actual !== input) {
    failed += 1;
    console.error(`KEEP 훼손\n  입력: ${input}\n  실제: ${JSON.stringify(actual)}`);
  }
}

if (failed) {
  console.error(`\n새니타이저 검사 실패 ${failed}건`);
  process.exit(1);
}
console.log(`새니타이저 검사 통과 — 제거 ${REMOVE.length}종 · 보존 ${KEEP.length}종`);
