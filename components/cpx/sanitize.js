// 환자 발화 새니타이저 — 모델이 프롬프트 금지에도 붙이는 안전 면책·상담 권고·AI 자기지칭
// 문구와 제어 태그를 자막·전사에서 제거한다. 방어층 — 근본 대응은 서버 시스템 프롬프트
// (services/cpx/server/prompt.py [역할 재확인] 블록). 오디오에는 남을 수 있음.
//
// v2: 고정 어순 정규식 나열 → 문장 단위 판정. 구버전은 "의사를 방문하세요"처럼 조사가
// 고정된 형태만 지워서 "의학적인 소견은 의사와 직접 만나서 상담하십시오" 같은 변형을 놓쳤다.
// 판정 원리: 환자는 의사(학생)에게 병원 방문·전문가 상담을 권고하지 않는다 — 의료 주체
// 키워드와 청자를 향한 권고 어미가 한 문장에 같이 오면 페르소나 이탈로 보고 문장째 버린다.
// 환자의 병력 진술("어제 병원에 갔어요")·질문("큰 병원에 가야 하나요?")은 권고 어미가
// 아니라서 통과한다.

const MEDICAL_TOPIC = /의사|의료|의학|병원|의원|응급실|119|전문의|전문가|진료|진찰|진단|검진|검사|상담/

// 청자를 향한 권고·지시 어미(문장 끝). 환자 화법(해요체 진술·과거형·질문)에는 나타나지
// 않는 형태만 나열한다. -시- 존칭이 붙은 가능형("받으실 수 있습니다")은 청자 대상 안내문.
const SENTENCE_TAIL = '\\s*[.!?…"\'”’)\\s]*$'

// (가) 무조건 청자를 향한 지시·권고. 환자가 의사에게 쓸 일이 없는 형태다.
const LISTENER_DIRECTIVE = new RegExp(
  '(?:' +
    [
      '십시오',
      '시(?:기|길)\\s*바랍니다',
      '기\\s*바랍니다',
      '바랍니다',
      '권장\\s*(?:합니다|됩니다|드립니다|드려요)',
      '권합니다',
      '권해\\s*드(?:립니다|려요)',
      '추천\\s*(?:합니다|드립니다|드려요)',
      '(?:하|가|받으)세요',
      '(?:해|아|어|와|가)\\s*보세요',
      '(?:는|시는)\\s*(?:것이|게)\\s*좋(?:습니다|겠습니다)',
      '시는\\s*(?:것이|게)\\s*좋(?:을\\s*것\\s*같아요|겠어요|아요)',
      '(?:하|받으|가|보)실\\s*수\\s*있습니다',
      // 존대형 당위("받으셔야 합니다")는 주어가 청자다 — 아래 서술 어미와 달리 무조건 권고.
      '(?:하|받으|가|보|오|드)셔야\\s*(?:합니다|해요|됩니다)',
    ].join('|') +
    ')' + SENTENCE_TAIL
)

// (나) 자기 사정을 말할 때도 쓰는 서술 어미. 이것만 보고 지우면 환자의 정상 대사가 사라진다 —
// "회사에 낼 진단서가 필요합니다", "저는 병원에 가야 합니다"가 통째로 삭제되고 있었다
// (2026-08-18 감사 다5). 청자를 향한 존대 표지가 함께 있을 때만 권고로 본다.
const SELF_OR_ADVICE_ENDING = new RegExp(
  '(?:(?<!불)가능합니다|필요합니다|(?:해야|받아야|가야)\\s*합니다)' + SENTENCE_TAIL
)
const ADDRESSES_LISTENER = /주시|주세요|셔야|하시는|하시면|받으시|가시면|오시는|하십|드리겠습니다/

// (다) 남의 말을 옮기는 문장은 권고가 아니다. "동네 의사 선생님이 그냥 쉬라고 하세요"의
// '하세요'는 청자에 대한 지시가 아니라 인용 동사다.
const REPORTED_SPEECH = /(?:라고|다고|자고|냐고|라며|다며|래요|대요|라는|다는)\s*(?:하|해|했|말|그러|얘기|이야기)/

// 어미와 무관하게 문장 자체가 면책·AI 자기지칭인 경우.
const HARD_BREAK_PATTERNS = [
  /(?:저|제)는\s*(?:AI|A\.I|인공\s*지능|언어\s*모델|챗봇|프로그램|가상|시뮬레이|모델)/,
  /(?:AI|인공\s*지능|언어\s*모델|챗봇)(?:로서|으로서|이므로|이라서|입니다)/,
  /(?:본|이|제)\s*(?:답변|응답|대화|내용|정보)(?:은|는)?[^.!?…]*(?:의학|의료|참고|조언|진단)/,
  /(?:의학적|의료적)[^.!?…]{0,12}(?:조언|소견|판단|진단|정보|자문)[^.!?…]*(?:아니|아닙|없|드릴\s*수|제공|한계|대체|불가)/,
  /진단(?:을|은)?[^.!?…]{0,6}(?:내릴|내려|드릴|제공할)\s*수(?:는|가)?\s*없/,
  /참고용|면책/,
  // v3: 자기 발화 해설 라벨. 모델이 대사 뒤에 그 대사가 무엇인지 꼬리표를 붙인다
  // ("…아파요. " 비의료적 질문에 대한 답변입니다."). 면책 어휘도 권고 어미도 없어서
  // v2 판정을 그대로 통과했다. 환자는 자기 말을 분류·해설하지 않는다.
  /(?:질문|물음|요청|상황)에\s*대한\s*(?:답변|응답|대답)/,
  /(?:답변|응답)\s*(?:입니다|이었습니다|드립니다|드리겠습니다|드렸습니다|드리자면)/,
  /비\s*-?\s*의료(?:적|성)|의료\s*외(?:의)?\s*(?:질문|내용|영역)|진료\s*와\s*무관/,
  /역할\s*로서(?:의)?\s*(?:답변|응답|대답)/,
  /(?:규칙|지침|설정|시나리오|맥락)\s*(?:상|에\s*따라서?)\s*[^.!?…]{0,10}(?:답변|응답|대답|말씀|안내)/,
]

// 모델이 자기 사정을 설명할 때만 나오는 어휘. 환자 화법에는 없다.
const MODEL_VOCAB = /시스템\s*(?:프롬프트|지시|지침|메시지)|지시문|프롬프트|시뮬레이션|역할극|페르소나|표준화\s*환자|가상\s*환자/

// 못 알아듣고 되묻는 환자 반응. 어휘만 보고 지우면 이런 정상 대사까지 사라져 자막이 빈 턴이
// 된다 — 오디오는 이미 나간 뒤라 화면만 비는 게 더 나쁘다. 되묻는 문장은 이탈로 보지 않는다.
const CONFUSED_PATIENT = /네\?|예\?|무슨 말씀|모르겠|못 알아|뭔지|뭐예요|뭐래|뭔가요|다시 말씀/

// 문장 분리 때문에 되묻기가 조각난다("역할극이요? 무슨 말씀이신지 모르겠어요."의 앞 조각).
// 짧은 의문문은 들은 말을 그대로 되받는 환자 반응으로 보고 어휘 판정에서 면제한다.
function isEchoQuestion(sentence) {
  return /\?\s*$/.test(sentence) && sentence.length <= 20
}

// 가장자리 따옴표 제거 — 짝이 안 맞아도 버린다. 공통 프롬프트가 대사를 큰따옴표로 감싸게
// 하므로 문장 경계마다 따옴표가 붙어 오고, 중간 문장을 지우면 한쪽만 남는다.
function trimEdgeQuotes(s) {
  return s.replace(/^[\s"“”'‘’]+/, '').replace(/[\s"“”'‘’]+$/, '').trim()
}

// 의료 주제 + 권고 어미로만 판정하면 환자가 자기 사정을 말하거나 남의 말을 옮기는 문장까지
// 지운다. 권고가 '청자를 향한 것'임이 드러날 때만 이탈로 본다.
function isAdviceToListener(sentence) {
  if (REPORTED_SPEECH.test(sentence)) return false
  if (LISTENER_DIRECTIVE.test(sentence)) return true
  return SELF_OR_ADVICE_ENDING.test(sentence) && ADDRESSES_LISTENER.test(sentence)
}

function isPersonaBreak(sentence) {
  for (const p of HARD_BREAK_PATTERNS) if (p.test(sentence)) return true
  if (MODEL_VOCAB.test(sentence) && !CONFUSED_PATIENT.test(sentence) && !isEchoQuestion(sentence)) return true
  return MEDICAL_TOPIC.test(sentence) && isAdviceToListener(sentence)
}

// 환자 발화 텍스트에서 페르소나 이탈 문장(면책·상담 권고·AI 자기지칭)과 제어 태그를 제거한다.
// 순수 면책 턴은 빈 문자열이 되고, 호출부(onPatientText)가 빈 값을 스킵한다.
export function sanitizePatientText(text) {
  let out = String(text || '')
  out = out.replace(/\[SYS_EVENT[^\]]*\]/gi, '')
  out = out.replace(/\[[^\]]{0,40}\]/g, '') // 남은 짧은 대괄호 지문 (예: [당황])
  out = out.replace(/\s{2,}/g, ' ').trim()
  if (!out) return ''
  // 문장 분리: 종결부호 뒤에서 자르되 소수점("38.5도")·부호 연속("?!")은 유지.
  const sentences = out.split(/(?<=[.!?…])(?![\d.!?…])\s*|\n+/)
  out = sentences
    .map((s) => trimEdgeQuotes(s.trim()))
    .filter((s) => s && !isPersonaBreak(s))
    .join(' ')
  return trimEdgeQuotes(out)
}
