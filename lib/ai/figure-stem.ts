/**
 * "발문이 그림을 가리키는가" 판정 — 순수 함수만 둔다.
 *
 * 왜 별도 파일인가: private-generation.ts 는 Anthropic SDK·PDF 파서를 끌고 오므로
 * 스크립트에서 import 하면 모듈 해석부터 실패한다. blind-policy.ts·verify-policy.ts 와
 * 같은 이유·같은 모양이다 — 이 판정은 회귀 검사가 반드시 지켜야 하는 결정이라
 * 무거운 의존이 없는 잎 모듈에 둔다.
 *
 * 왜 회귀 검사가 필요한가 (2026-08-22 실측)
 * ────────────────────────────────────────
 * 이 판정이 조용히 실패하면 **학생이 못 푸는 문항**이 그대로 저장된다. 발문은
 * "제시된 MRI 영상은 …"인데 화면에는 그림이 없는 상태다. 저장도 정상이고 문항 수도
 * 맞아서 로그에는 흔적이 남지 않는다 — 사람이 화면을 보기 전에는 아무도 모른다.
 * 실제로 두 번 났다: "다음은 복부 초음파 소견이다"(꼬리 명사 누락)와
 * "제시된 MRI 영상은"(꼬리 조사에 은/는 없음 + 괄호 원어가 서술어를 끊음).
 *
 * ⚠ 이 파일에는 **import 를 두지 않는다**(blind-policy.ts·verify-policy.ts 와 같은 규칙).
 *   표식 문항("A로 표시된 …") 판정은 annotate-markers.ts 의 stemReferencesMarker 가 맡고,
 *   두 판정의 결합(OR)은 호출부인 private-generation.ts 에서 한다. 여기로 import 를
 *   끌어오면 스크립트가 이 모듈을 못 불러와 회귀 검사 자체가 사라진다.
 */

const IMAGE_DEIXIS = '다음|아래|위의|위에|제시된|해당|보이는|첨부된|주어진';
// 모식도·도해 같은 "그림" 표현을 빠뜨려 실제 사고가 났다(발문은 "…모식도이다"인데 이미지 없음).
const IMAGE_NOUNS =
  '그림|사진|이미지|영상|심전도|ECG|EKG|방사선|엑스레이|X-?ray|CT|MRI|초음파|병리|현미경|소견|' +
  '모식도|도해|도식|개념도|삽화|도표';
// 그림을 "선언"하는 발문에 쓰이는 명사(표·그래프처럼 본문에 글로 넣을 수 있는 것은 제외).
const FIGURE_NOUNS =
  '그림|사진|이미지|영상|모식도|도해|도식|개념도|삽화|심전도|ECG|EKG|X-?ray|엑스레이|방사선\\s*사진|CT|MRI|초음파|현미경\\s*사진|병리\\s*소견';
// 그림 명사와 서술어 사이에 흔히 끼는 명사("초음파 소견이다", "CT 영상이다").
// 실측 사고: "다음은 복부 초음파 소견이다" 가 이 틈 때문에 '그림 선언'으로 안 잡혀,
// 이미지가 붙지 않은 채로 학생에게 나갔다.
// 주의: 조사 목록에 '은/는' 을 넣지 않아 "심전도 소견은 정상이었다"(본문 서술)는 계속 제외된다.
const FIGURE_TAIL_NOUN = '(?:\\s*(?:소견|사진|영상|결과|이미지))?';
// 그림 명사 뒤에 붙는 괄호 원어("확산 스펙트럼 영상(Diffusion Spectrum Imaging)이다").
// 2026-08-22 실측: 이 괄호가 명사와 서술어 사이를 끊어 선언형이 통째로 미검출됐다.
const FIGURE_PAREN = '(?:\\s*\\([^)]{0,60}\\))?';
// 조사 뒤가 **과거 서술 종결**이면 그림 지칭이 아니라 본문에 소견을 적은 것이다
// ("다음 환자의 심전도 소견은 정상이었다"). 그림 지칭은 "…이다/…보여준다/…는?"으로 이어진다.
// 지시어를 빼는 대신 이 서술어 차이로 구분한다 — 지시어를 빼면 "다음 그림은 …"까지 놓친다.
const NARRATED_TAIL = '(?!\\s*[^.?!\\n]{0,12}(?:이었|였|았|었)다)';

const IMAGE_DEPENDENT_STEM_RE = new RegExp(
  // 지시어와 명사 사이에 수식어가 끼어드는 형태까지 잡는다("아래 흉부 X-ray 를 보고").
  `(?:${IMAGE_DEIXIS})\\s*(?:[가-힣A-Za-z0-9]{1,6}\\s*){0,2}(?:${IMAGE_NOUNS})|` +
    `(?:${IMAGE_NOUNS})\\s*(?:에서|에는|을|를|의|상)\\s*(?:관찰|보이|나타|판독|해석)|` +
    // "다음은 대동맥 박리의 발생 기전에 대한 모식도이다" 처럼 지시어와 그림 명사 사이에
    // 설명이 길게 끼는 선언형. 명사 뒤 조사로 "그림을 가리키는 문장"임을 확인해
    // "심전도 소견은 정상이었다"(본문에 소견을 서술한 경우)와 구분한다.
    `(?:다음|아래|위)(?:은|는)?\\s*[^.?!\\n]{0,40}?(?:${FIGURE_NOUNS})${FIGURE_TAIL_NOUN}\\s*(?:이다|입니다|이며|이고|에서|에는|을|를)|` +
    `판독(?:하|해)|사진\\s*판독`,
  'i',
);

const FIGURE_DECLARATION_RE = new RegExp(
  // (a) 선언형 — "다음은 …모식도이다", "다음은 복부 초음파 소견이다".
  //     꼬리 조사에 '은/는'을 넣지 않는다: "다음 환자의 심전도 소견은 정상이었다"(본문 서술)를
  //     그림 지칭으로 오인하지 않기 위해서다.
  `(?:다음|아래|위|제시된|첨부된|주어진)(?:은|는)?\\s*[^.?!\\n]{0,40}?(?:${FIGURE_NOUNS})${FIGURE_TAIL_NOUN}${FIGURE_PAREN}` +
    `\\s*(?:이다|입니다|이며|이고|에서|에는|으로|로|를\\s*보고|을\\s*보고|를\\s*판독|을\\s*판독)|` +
    // (b) 지시어가 그림 명사를 **직접 수식**하는 형태 — "제시된 MRI 영상은", "다음 그림은".
    //
    //     (a) 가 '은/는'을 못 받아서 이 형태를 통째로 놓쳤다(2026-08-22 실측: 이미지 없이 그림을
    //     가리키는 문항 4건 중 4건 미검출 — 학생이 못 푸는 문항이 그대로 저장됐다).
    //
    //     처음에는 '다음'을 뺐다. "다음 환자의 심전도 소견은 정상이었다"(본문 서술)가 걸릴까 봐
    //     그랬는데, 그 바람에 **가장 흔한 형태인 "다음 그림은 …"** 이 그대로 빠져 같은 사고가
    //     또 났다(2026-08-22 2차 실측: 스크린샷 3번 문항). 지시어를 빼는 건 해법이 아니었다.
    //
    //     진짜 구분점은 지시어가 아니라 **서술어**다. 그림 지칭은 "…이다/…보여준다/…는?"으로
    //     이어지고, 본문 서술은 "…정상이었다"처럼 과거 종결로 끝난다. 그래서 '다음'을 다시
    //     넣되 NARRATED_TAIL 로 과거 서술만 배제한다. 이렇게 하면 "다음 환자의 흉부 X-ray는?"
    //     (국시 기본형)도 정상으로 잡힌다 — 종전 규칙에서는 이것도 놓쳤다.
    `(?:다음|아래|위의|위에|제시된|첨부된|주어진)\\s*(?:[가-힣A-Za-z0-9-]{1,15}\\s*){0,3}` +
    `(?:${FIGURE_NOUNS})${FIGURE_TAIL_NOUN}${FIGURE_PAREN}\\s*(?:은|는|이|가|을|를|에서|에는)${NARRATED_TAIL}|` +
    // (c) 지시어 없이 검사명으로 그림을 가리키는 형태 — "흉부 X-ray와 MR 영상에서 보이는
    //     대동맥 병변의 진단은?", "CT에서 관찰되는 소견은?".
    //
    //     2026-08-27 실측(업로드 effbfdf0 슬롯 7): 이 발문의 이미지가 모달리티 불일치로
    //     떨어져 나갔는데, (a)(b) 모두 지시어(다음·제시된)를 요구해서 못 잡았다 → 그림 없는
    //     채로 저장·노출. 핵심은 "검사명 + 에서 + 보이는/관찰되는 + **일반 명사**(병변·소견)".
    //     뒤에 오는 명사가 구체적 소견("종격동 확장")이면 본문에 소견을 적은 것이라 잡지
    //     않는다 — 그런 문항은 그림 없이도 풀린다. 과거 서술("…정상이었다")도 제외한다.
    `(?:${FIGURE_NOUNS})(?:\\s*(?:영상|사진))?\\s*(?:에서|상에서|상)\\s*` +
    `(?:보이는|관찰되는|나타나는|확인되는|관찰된|보인|나타난)\\s*` +
    `(?:[가-힣A-Za-z0-9-]{1,10}\\s*){0,3}(?:병변|소견|이상|구조|부위|변화|음영|종괴|결절)` +
    `(?:의|으로|을|를|은|는|이|가)${NARRATED_TAIL}`,
  'i',
);

/**
 * 발문이 "제시된 그림을 봐야만 풀리는" 문항인지 판정(느슨) — 표식 판정 제외.
 *
 * 이미지가 정제(텍스트 제거) 실패나 재사용 상한으로 빠지면, 그림을 가리키는 발문은
 * 풀 수 없으므로 문항을 삭제해야 한다. 반대로 모델이 이미지를 곁들이기만 하고 발문은
 * 텍스트만으로 완결된 경우(흔함)까지 삭제하면 요청 수가 모자라 보충 생성이 돌고,
 * 그 보충 호출이 전체 시간을 수십 초 늘린다. 그래서 발문 표현으로 구분한다.
 * (판정이 애매하면 삭제 쪽으로 — 못 푸는 문항을 남기는 것이 더 나쁘다.)
 */
export function stemDependsOnImageText(stem: string): boolean {
  const s = String(stem ?? '');
  // 엄격한 판정을 **항상 포함**한다(느슨 ⊇ 엄격).
  //
  // 두 정규식을 따로 키우다 보면 한쪽만 고쳐져 "그림을 선언했다고 판정되는데 그림에
  // 의존하지는 않는다"는 모순이 생긴다. 실제로 2026-08-22 실측에서 괄호 원어가 낀
  // 선언형("…확산 스펙트럼 영상(Diffusion Spectrum Imaging)이다")이 엄격 판정에는
  // 잡히고 느슨 판정에는 안 잡혔다 — 그러면 이미지가 정제 실패로 빠졌을 때 그 문항이
  // 삭제되지 않고 그림 없는 채로 남는다. 포함 관계를 코드로 박아 드리프트를 막는다.
  return IMAGE_DEPENDENT_STEM_RE.test(s) || FIGURE_DECLARATION_RE.test(s);
}

/**
 * "제시된 그림을 가리키는" 발문인지 더 엄격하게 판정한다 — 표식 판정 제외.
 *
 * 용도 차이:
 *  - stemDependsOnImage: 모델이 image_indices 를 채웠는데 이미지가 정제 실패로 빠진 경우에 쓴다.
 *    이미 그림을 의도한 문항이므로 느슨해도 된다.
 *  - stemDeclaresFigure: 이미지가 애초에 하나도 연결되지 않은 문항을 지울지 판단한다.
 *    오탐이면 멀쩡한 문항을 지우게 되므로, 그림 명사 뒤 조사까지 확인해
 *    "다음 환자의 심전도 소견은 정상이었다"(본문 서술)와 "…모식도이다"(그림 지칭)를 구분한다.
 */
export function stemDeclaresFigureText(stem: string): boolean {
  return FIGURE_DECLARATION_RE.test(String(stem ?? ''));
}
