/**
 * 배치 단위 지식형 정량 지시.
 *
 * 임상형 쿼터(buildClinicalQuotaDirective)와 같은 이유로 필요하다 — 배치가 병렬로 독립
 * 판단하므로 "유형을 흩어라"를 시스템 프롬프트에만 두면 배치마다 같은 유형(치료·총론)으로
 * 몰린다. 이번 묶음이 쓸 발문 유형을 **코드가 배정해** 넘긴다.
 */
export function buildKnowledgeQuotaDirective(input: {
  batchSize: number;
  quota: number;
  /** 이 묶음에 배정된 발문 유형(코드가 라운드로빈으로 배분). */
  assignedAskKinds: readonly string[];
  /** 이 묶음에서 부정형("옳지 않은 것은?")을 허용하는지. */
  allowNegative: boolean;
}): string {
  const { batchSize, quota, assignedAskKinds, allowNegative } = input;
  if (quota <= 0) return '';
  const all = quota >= batchSize;
  const kindList = assignedAskKinds
    .map((k) => `\`${k}\`(${ASK_KIND_LABELS[k as AskKind] ?? k})`)
    .join(', ');
  return (
    `\n\n**지식형 최소 ${quota}문항**: 이번 묶음 ${batchSize}문항 중 ` +
    (all ? '**전부**를 ' : `최소 ${quota}문항을 `) +
    '위 K0~K7 규격의 지식형으로 만드세요. ' +
    (kindList
      ? `이번 묶음의 발문 유형은 ${kindList} 로 **배정**되어 있습니다 — 나열된 순서대로 하나씩 맡아 ` +
        '각 문항의 `ask_kind` 에 그 값을 그대로 적으세요. 같은 유형을 두 번 쓰지 않습니다. ' +
        '자료가 배정된 유형을 도저히 뒷받침하지 못할 때만 다른 유형으로 바꾸되, ' +
        '그 경우 `concepts` 의 마지막 항목에 `#유형변경:<배정값>→<사용값>` 을 남기세요 ' +
        '(다른 묶음이 그 유형을 맡고 있으므로 임의로 바꾸면 문제집 전체가 같은 유형으로 쏠립니다). '
      : '각 문항의 `ask_kind` 를 서로 다르게 정하세요. ') +
    '**"가장 적절한", "가장 가능성 높은", "다음 중"은 발문에 쓰지 마세요**("가장 흔한 ~은?" 제외). ' +
    '"~에 대한 설명으로 옳은 것은?" 형태는 이번 묶음에서 **최대 1문항**입니다. ' +
    (allowNegative
      ? '부정형("옳지 않은 것은?")은 이번 묶음에서 최대 1문항까지 허용합니다. '
      : '부정형("옳지 않은 것은?", "거리가 먼 것은?")은 이번 묶음에서 **쓰지 마세요.** ') +
    '환자 나이·성별로 시작하는 증례형 도입은 지식형으로 세지 않습니다.'
  );
}
