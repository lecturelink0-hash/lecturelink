const ASK_TYPE_MIX = '진단 30% : 치료·약물 25% : 처치·조치 17% : 검사 13% : 기타 15%';

/**
 * 문항 생성용 사용자 메시지 빌더
 */
export function buildGenerationUserMessage(input: {
  subjectName: string;
  subTopicName: string;
  examRelevance: 1 | 2 | 3;
  isRiskCategory: boolean;
  difficulty: 1 | 2 | 3;
  style: 'kmle' | 'professor' | 'internal';
  /**
   * 스타일 학습용 few-shot 예시.
   *
   * 주의: 검수를 통과한 문항(tier='curated')만 넣어야 한다. 기존 풀의 임의 문항을
   * 그대로 넣으면 그 문항의 형식 결함이 새 문항으로 복제된다. 기출 원문은 저작권
   * 문제로 넣을 수 없다.
   */
  examples?: Array<{ stem: string; choices: string[]; explanation: string }>;
  count: number;
  /**
   * 사용자 메시지에 실제 이미지가 함께 실려 있는지.
   *
   * 이미지는 텍스트와 별개 블록으로 붙어 있어 지시가 없으면 모델이 그림을 무시하고
   * 텍스트만으로 문항을 만들어 버린다. F11·F23 이 갈리는 지점이라 명시적으로 알린다.
   */
  hasImage?: boolean;
}): string {
  const styleDesc =
    input.style === 'kmle'
      ? 'KMLE(국가고시) 스타일 — 위 F01~F23 규격을 그대로 적용'
      : input.style === 'professor'
        ? '대학 교수 출제 스타일 — 강의 내용 기반, 개념 심화. 형식은 F01~F23 을 따른다.'
        : '내신 시험 스타일 — 학교 정기시험 수준. 형식은 F01~F23 을 따른다.';

  const fewShot = input.examples?.length
    ? `\n\n## 참고 예시 (스타일 학습용 — 내용이 아니라 형식만 참고)\n\n${input.examples
        .map(
          (ex, i) => `### 예시 ${i + 1}
**문제**: ${ex.stem}
**선지**: ${ex.choices.map((c, j) => `${j + 1}. ${c}`).join(' / ')}
**해설**: ${ex.explanation}`,
        )
        .join('\n\n')}`
    : '';

  const mix =
    input.count > 1
      ? `\n- 발문 유형을 섞는다. 실제 국시 분포는 ${ASK_TYPE_MIX} 이다.`
      : '';

  const imageRule = input.hasImage
    ? `
- **이 메시지에 사진이 첨부돼 있다. 사진을 판독해 문항을 만든다.**
  - 사진 지칭은 F11 형식으로 **한 문장만** 쓴다.
  - **사진에서 읽어야 할 소견은 글로 적지 않는다.** 참고 예시의 발문·해설이 소견을 글로 적고 있어도 따라 쓰지 않는다.
    - ✗ "가슴 X선사진(사진 1)에서 종격동 확장이 관찰된다." — 소견을 알려 줘 사진을 안 봐도 풀린다
    - ○ "가슴 X선사진(사진 1)이다."`
    : '';

  return `
다음 조건으로 ${input.count}개의 의학 문항을 생성하세요.

## 영역
- 과목: ${input.subjectName}
- Sub-topic: ${input.subTopicName}
- KMLE 빈출도: ${'★'.repeat(input.examRelevance)}
- 위험 영역 여부: ${input.isRiskCategory ? '★★★ 예 (보수적 작성 필수)' : '아니오'}
- 목표 난이도: ${input.difficulty} / 3

## 스타일
${styleDesc}
${fewShot}

## 요구사항
- ${input.count}개의 서로 다른 임상 시나리오 (환자 정보·검사 결과·증상 다양화)
- 같은 sub-topic이지만 평가 포인트가 겹치지 않도록
- 각 문항은 독립적으로 풀 수 있어야 함 (의존 관계 X)${mix}${imageRule}
- 제출 전 자기 점검 10항목을 모두 통과시킬 것

generate_questions 도구로 응답하세요.
`.trim();
}

